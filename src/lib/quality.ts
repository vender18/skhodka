/**
 * Проверка черновика перед отправкой.
 *
 * Запреты из промта модель соблюдает через раз: на живых новостях она уверенно
 * писала «высокопроизводительный» и «фирменный», хотя оба слова стоят в списке
 * запрещённых. Поэтому то, что можно проверить механически, проверяем кодом
 * и отправляем на переписывание с конкретным замечанием.
 */

/** Слова и обороты, по которым текст сразу читается как пресс-релиз. */
