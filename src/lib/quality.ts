/**
 * Проверка черновика перед отправкой.
 *
 * Запреты из промта модель соблюдает через раз: на живых новостях она уверенно
 * писала «высокопроизводительный» и «фирменный», хотя оба слова стоят в списке
 * запрещённых. Поэтому то, что можно проверить механически, проверяем кодом
 * и отправляем на переписывание с конкретным замечанием.
 */

/** Слова и обороты, по которым текст сразу читается как пресс-релиз. */
const BANNED = [
  'высокопроизводительн',
  'инновационн',
  'переосмысл',
  'уникальн',
  'фирменн',
  'стремлен',
  'презентова',
  'продемонстрирова',
  'культов',
  'легендарн',
  'знаков',
  'шедевр',
  'не оставит равнодушн',
  'взорвал интернет',
  'в рамках',
  'является',
  'осуществ',
  'данный проект',
  'расширяя границы',
  'привноси',
];

/**
 * Продающие обороты и выдуманные выводы.
 *
 * Модель почти всегда дописывает в конце предложение, которого нет в
 * источнике: кому коллекция «предназначена», кто её «оценит» и что надо
 * «успеть». Это одновременно и реклама, и главный источник выдумок —
 * именно в таком предложении она сочинила, что вещи «доступны только
 * в цифровом виде», хотя они продаются в обычных магазинах.
 */
const SALES_PITCH = [
  'успейте',
  'спешите',
  'не пропустите',
  'пока они в наличии',
  'пока есть в наличии',
  'предназначен для тех',
  'предназначена для тех',
  'рассчитан на тех',
  'рассчитана на тех',
  'для тех, кто ценит',
  'порадует',
  'оценят по достоинству',
  'придётся по вкусу',
  'станет отличным',
  'идеально подойдёт',
];

/** Обороты пересказа чужой статьи вместо новости. */
const RETELLING = [
  'в статье',
  'в материале',
  'автор отмечает',
  'автор пишет',
  'издание пишет',
  'в публикации',
  'рассматриваются',
  'перечислены',
];

export interface QualityIssue {
  kind: 'banned' | 'retelling' | 'source-named' | 'too-long' | 'sales-pitch';
  detail: string;
}

/**
 * Приводит текст в порядок: убирает markdown, который модель добавляет вопреки
 * запрету, и чинит неразрывные дефисы — Telegram показывает их как обычные,
 * но при копировании в редактор они ломают вёрстку.
 */
export function normalize(text: string): string {
  return text
    .replace(/‑/g, '-') // неразрывный дефис
    .replace(/ /g, ' ') // неразрывный пробел
    .replace(/^#{1,6}\s+/gm, '') // заголовки markdown
    .replace(/\*\*(.+?)\*\*/g, '$1') // жирный
    .replace(/(^|\s)\*(\S[^*]*?)\*(?=\s|$)/g, '$1$2') // курсив
    .replace(/^[-*]\s+/gm, '— ') // списки
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

/** Ищет в тексте то, что делает его непригодным для канала. */
export function findIssues(text: string, sourceNames: string[]): QualityIssue[] {
  const lower = text.toLowerCase();
  const issues: QualityIssue[] = [];

  const banned = BANNED.filter((word) => lower.includes(word));
  if (banned.length > 0) {
    issues.push({
      kind: 'banned',
      detail: `запрещённые слова: ${banned.join(', ')}`,
    });
  }

  const pitch = SALES_PITCH.filter((phrase) => lower.includes(phrase));
  if (pitch.length > 0) {
    issues.push({
      kind: 'sales-pitch',
      detail:
        `в конце дописан рекламный вывод, которого нет в источнике (${pitch.join(', ')}). ` +
        'Закончи текст фактом, а не рассуждением о том, кому это понравится',
    });
  }

  const retelling = RETELLING.filter((phrase) => lower.includes(phrase));
  if (retelling.length > 0) {
    issues.push({
      kind: 'retelling',
      detail: `текст пересказывает чужую статью вместо того, чтобы сообщить новость: ${retelling.join(', ')}`,
    });
  }

  const named = sourceNames.filter((name) => name.length > 3 && lower.includes(name.toLowerCase()));
  if (named.length > 0) {
    issues.push({
      kind: 'source-named',
      detail: `в тексте назван источник: ${named.join(', ')}`,
    });
  }

  if (text.length > 900) {
    issues.push({ kind: 'too-long', detail: `${text.length} знаков вместо 600` });
  }

  return issues;
}

/** Собирает замечание для повторной попытки. */
export function rewriteInstruction(issues: QualityIssue[]): string {
  return [
    'Перепиши текст. Что не так:',
    ...issues.map((issue) => `— ${issue.detail}`),
    '',
    'Верни только исправленный текст поста, без пояснений.',
  ].join('\n');
}
