const ALL = [...HARD_STOP, ...SPORT_ROUTINE, ...COMMERCE, ...NO_NEWS_HOOK];

/**
 * Стоит ли вообще показывать материал модели.
 * Возвращает причину отсева либо null, если материал проходит дальше.
 */
export function prefilterReason(title: string, summary: string | null): string | null {
  const text = `${title} ${summary ?? ''}`.toLowerCase();

  for (const word of ALL) {
    if (text.includes(word)) return word;
  }
  return null;
}
